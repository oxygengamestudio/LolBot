export function getLocale(locale: string | null | undefined): LocaleKey {
    if (locale && locale.toLowerCase().startsWith('fr')) {
        return 'fr';
    }
    return 'en';
}

export async function resolveLocale(guildId?: string | null, fallbackLocale?: string | null): Promise<LocaleKey> {
    if (guildId) {
        try {
            const settings = await guildSettingsManager.getSettings(guildId);
            const localeConfigured = await guildSettingsManager.isLocaleConfigured(guildId);
            if (localeConfigured) {
                return getLocale(settings.locale);
            }
            return getLocale(fallbackLocale ?? settings.locale);
        } catch {
            // Ignore and fallback.
        }
    }
    return getLocale(fallbackLocale);
}

export function t(locale: string | null | undefined, key: string, vars?: Record<string, string | number>): string {
    const resolvedLocale = getLocale(locale);
    const template = translations[resolvedLocale][key] ?? translations.en[key] ?? key;

    if (!vars) {
        return template;
    }

    return template.replace(/\{(\w+)\}/g, (match, name) => {
        const value = vars[name];
        return value === undefined ? match : String(value);
    });
}

export function localeLabel(locale: LocaleKey): string {
    return t(locale, `settings.languageValue.${locale}`);
}

export function booleanLabel(locale: string | null | undefined, value: boolean): string {
    return t(locale, value ? 'common.yes' : 'common.no');
}

export function modeLabel(
    locale: string | null | undefined,
    mode: 'allow_all' | 'whitelist' | 'blacklist',
    count: number
): string {
    return t(locale, `settings.mode.${mode}`, { count });
}

export function commandDescriptionLocalizations(fr: string, en: string): LocalizationMap {
    return {
        fr,
        'en-US': en,
        'en-GB': en,
    };
}
